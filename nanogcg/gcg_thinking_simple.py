def extract_thinking_content(generated_text: str, start_tag: str = "<thinking>", end_tag: str = "</thinking>") -> str:
    """Extract content between thinking tags from generated text.

    Args:
        generated_text: The text generated by the model
        start_tag: The start tag (default: "<thinking>")
        end_tag: The end tag (default: "</thinking>")

    Returns:
        The content between thinking tags, empty string if no tags found
    """
    # Escape special regex characters in tags
    escaped_start = re.escape(start_tag)
    escaped_end = re.escape(end_tag)

    # Find content between start and end tags
    pattern = f'{escaped_start}(.*?){escaped_end}'
    matches = re.findall(pattern, generated_text, re.DOTALL)

    if not matches:
        return ""

    # Return the longest thinking content if multiple matches exist
    return max(matches, key=len)


